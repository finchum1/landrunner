import assert from 'node:assert/strict';
import { entryAmount, filterEntries, rangeFor, summarize } from '../src/lib/billing.ts';
const e = (kind: any, quantity: number, over: any = {}): any => ({ id: Math.random() + '', kind, quantity, amount: null, entry_date: '2026-11-10', billed_at: null, ...over });
const rates = { hourly: 75, mileage: 0.7 };
assert.equal(entryAmount(e('hours', 2.5), rates), 187.5);
assert.equal(entryAmount(e('miles', 100), rates), 70);
assert.equal(entryAmount(e('expense', 0, { amount: 12.34 }), rates), 12.34);
assert.equal(entryAmount(e('hours', 1), { hourly: null, mileage: 1 }), null);
const s = summarize([e('hours', 2.5), e('hours', 1), e('miles', 100), e('expense', 0, { amount: 20 })], rates);
assert.deepEqual(s, { hours: 3.5, miles: 100, laborTotal: 262.5, mileageTotal: 70, expenseTotal: 20, total: 352.5, missingRate: false });
assert.equal(summarize([e('hours', 1)], { hourly: null, mileage: null }).missingRate, true);
assert.deepEqual(rangeFor('this_month', '2026-11-23'), { from: '2026-11-01', to: '2026-11-30' });
assert.deepEqual(rangeFor('last_month', '2026-11-23'), { from: '2026-10-01', to: '2026-10-31' });
assert.deepEqual(rangeFor('last_month', '2026-01-05'), { from: '2025-12-01', to: '2025-12-31' });
assert.deepEqual(rangeFor('this_month', '2026-12-05'), { from: '2026-12-01', to: '2026-12-31' });
const list = [e('hours', 1, { entry_date: '2026-10-31' }), e('hours', 1, { entry_date: '2026-11-01' }), e('hours', 1, { entry_date: '2026-11-30', billed_at: '2026-12-01' })];
assert.equal(filterEntries(list, rangeFor('this_month', '2026-11-23'), false).length, 2);
assert.equal(filterEntries(list, rangeFor('this_month', '2026-11-23'), true).length, 1);
console.log('BILLING OK');
